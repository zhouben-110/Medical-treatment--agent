async def seed_guidelines() -> int:
    """将指南文本切片后写入 pgvector。幂等：每次运行追加，不会删除已有数据。"""
    settings = get_mcp_settings()

    splitter = RecursiveCharacterTextSplitter(
        chunk_size=500,
        chunk_overlap=50,
        separators=["\n\n", "\n", "。", "；", "，", " "],
    )

    all_texts = []
    all_metadatas = []
    for g in GUIDELINES:
        chunks = splitter.split_text(g["text"])
        for chunk in chunks:
            all_texts.append(chunk)
            all_metadatas.append({"source": g["title"]})

    if not all_texts:
        logger.warning("No guideline texts to seed.")
        return 0

    store = PGVector.from_existing_index(
        embedding=get_embeddings(),
        collection_name=COLLECTION_NAME,
        connection=settings.psycopg_url,
        use_jsonb=True,
    )

    # langchain-postgres add_texts (sync, run in thread)
    await asyncio.to_thread(store.add_texts, all_texts, all_metadatas)
    logger.info("Seeded %d guideline chunks from %d guidelines.", len(all_texts), len(GUIDELINES))
    return len(all_texts)


if __name__ == "__main__":
    n = asyncio.run(seed_guidelines())
    print(f"Seeded {n} guideline chunks.")
